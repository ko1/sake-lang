-- INSERT ... SELECT with a compound select and its own ORDER BY
CREATE TABLE a (v INTEGER);
CREATE TABLE b (v INTEGER);
CREATE TABLE merged (id INTEGER PRIMARY KEY, v INTEGER UNIQUE);
INSERT INTO a VALUES (30), (10);
INSERT INTO b VALUES (20), (10);
INSERT INTO merged (v) SELECT v FROM a UNION SELECT v FROM b ORDER BY v DESC;
SELECT id, v FROM merged ORDER BY id;
INSERT INTO merged (v) SELECT v FROM a UNION ALL SELECT v + 1 FROM b;
INSERT INTO merged (v) SELECT v + 5 FROM a INTERSECT SELECT v + 5 FROM b;
SELECT id, v FROM merged ORDER BY id;
INSERT INTO merged SELECT 100, 1 EXCEPT SELECT 100, 2;
SELECT count(*), max(id) FROM merged;
