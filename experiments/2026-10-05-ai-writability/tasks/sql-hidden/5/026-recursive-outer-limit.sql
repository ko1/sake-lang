-- recursive ctes combined with ORDER BY, LIMIT and joins in the outer query
CREATE TABLE coin (v INTEGER);
INSERT INTO coin VALUES (1), (5);
WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 20) SELECT i FROM n WHERE i % 7 = 0 ORDER BY i DESC;
WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 10) SELECT i FROM n ORDER BY i DESC LIMIT 3 OFFSET 2;
WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 3) SELECT i, v, i * v FROM n, coin ORDER BY i * v, i;
WITH RECURSIVE sq(i, s) AS (SELECT 1, 1 UNION ALL SELECT i + 1, (i + 1) * (i + 1) FROM sq WHERE i < 30) SELECT count(*) FROM sq WHERE s BETWEEN 100 AND 500;
