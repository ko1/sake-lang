-- rows compare as in SELECT DISTINCT: NULLs are equal to each other
CREATE TABLE l (k INTEGER, v TEXT);
CREATE TABLE r (k INTEGER, v TEXT);
INSERT INTO l VALUES (NULL, 'x'), (1, NULL), (2, 'y');
INSERT INTO r VALUES (NULL, 'x'), (1, NULL), (3, 'z');
SELECT k, v FROM l INTERSECT SELECT k, v FROM r ORDER BY k;
SELECT k, v FROM l EXCEPT SELECT k, v FROM r ORDER BY k;
SELECT k, v FROM l UNION SELECT k, v FROM r ORDER BY k NULLS LAST, v;
SELECT k FROM l UNION SELECT k FROM r ORDER BY k DESC;
