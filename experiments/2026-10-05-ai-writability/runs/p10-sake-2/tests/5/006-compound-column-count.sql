-- every simple-select must have the same number of result columns
CREATE TABLE t (a INTEGER, b INTEGER);
INSERT INTO t VALUES (1, 2);
SELECT a FROM t UNION SELECT a, b FROM t;
SELECT a, b FROM t UNION ALL SELECT a FROM t;
SELECT a FROM t INTERSECT SELECT * FROM t;
SELECT * FROM t EXCEPT SELECT 1;
SELECT a FROM t UNION SELECT b FROM t UNION ALL SELECT a, b FROM t;
SELECT a, b FROM t UNION SELECT b, a FROM t ORDER BY 1;
