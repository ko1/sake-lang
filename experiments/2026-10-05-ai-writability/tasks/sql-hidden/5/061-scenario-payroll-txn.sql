CREATE TABLE worker (id INTEGER PRIMARY KEY, name TEXT NOT NULL, rate INTEGER NOT NULL);
CREATE TABLE hours (worker_id INTEGER, month INTEGER, h INTEGER, UNIQUE (worker_id, month));
CREATE TABLE payslip (worker_id INTEGER, month INTEGER, amount INTEGER NOT NULL, UNIQUE (worker_id, month));
