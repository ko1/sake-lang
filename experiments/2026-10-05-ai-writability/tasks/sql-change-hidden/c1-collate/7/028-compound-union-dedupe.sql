-- UNION / INTERSECT / EXCEPT use the collation of the first simple-select that gives the column one.
CREATE TABLE a (n TEXT COLLATE NOCASE);
CREATE TABLE b (m TEXT);
INSERT INTO a VALUES ('Oak'), ('elm');
INSERT INTO b VALUES ('OAK'), ('Pine'), ('elm');
SELECT count(*) FROM (SELECT n FROM a UNION SELECT m FROM b);
SELECT count(*) FROM (SELECT m FROM b UNION SELECT n FROM a);
SELECT count(*) FROM (SELECT 'PINE' UNION SELECT n FROM a UNION SELECT m FROM b);
SELECT upper(x) FROM (SELECT n AS x FROM a INTERSECT SELECT m FROM b) ORDER BY 1;
SELECT x FROM (SELECT m AS x FROM b INTERSECT SELECT n FROM a) ORDER BY 1;
SELECT x FROM (SELECT m AS x FROM b EXCEPT SELECT n FROM a) ORDER BY 1;
SELECT x FROM (SELECT m COLLATE NOCASE AS x FROM b EXCEPT SELECT n FROM a) ORDER BY 1;
