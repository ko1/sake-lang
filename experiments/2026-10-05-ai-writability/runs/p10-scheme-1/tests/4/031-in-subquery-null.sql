-- IN with a subquery follows the IN-list rules, including NULLs.
CREATE TABLE a (x INTEGER);
CREATE TABLE b (y INTEGER);
INSERT INTO a VALUES (1), (2), (NULL);
INSERT INTO b VALUES (2), (NULL), (3);
SELECT x, x IN (SELECT y FROM b), x NOT IN (SELECT y FROM b) FROM a ORDER BY x;
SELECT x, x IN (SELECT y FROM b WHERE y IS NOT NULL) FROM a ORDER BY x;
SELECT count(*) FROM a WHERE x NOT IN (SELECT y FROM b);
SELECT count(*) FROM a WHERE x NOT IN (SELECT y FROM b WHERE y IS NOT NULL);
SELECT x FROM a WHERE NOT (x IN (SELECT y FROM b)) ORDER BY x;
