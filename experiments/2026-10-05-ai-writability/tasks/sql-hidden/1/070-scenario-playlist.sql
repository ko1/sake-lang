SELECT title, secs / 60 AS m, secs % 60 AS s FROM track ORDER BY pos;
SELECT title FROM track WHERE secs > 240 ORDER BY secs DESC;
SELECT title, artist FROM track WHERE artist = 'Oto' OR artist = 'oto' ORDER BY title;
