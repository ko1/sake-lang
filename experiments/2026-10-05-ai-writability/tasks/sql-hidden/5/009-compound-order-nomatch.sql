-- ORDER BY terms that match no result column of the compound
CREATE TABLE t1 (a INTEGER, b TEXT);
CREATE TABLE t2 (a INTEGER, b TEXT);
INSERT INTO t1 VALUES (1, 'p');
INSERT INTO t2 VALUES (2, 'q');
SELECT a FROM t1 UNION SELECT a FROM t2 ORDER BY b;
SELECT a AS lead, b FROM t1 UNION ALL SELECT a, b FROM t2 ORDER BY lead, b, missing;
SELECT a FROM t1 INTERSECT SELECT a FROM t2 ORDER BY 1, c;
SELECT a, b FROM t1 UNION SELECT a, b FROM t2 ORDER BY 3;
SELECT a, b FROM t1 UNION SELECT a, b FROM t2 ORDER BY b DESC;
