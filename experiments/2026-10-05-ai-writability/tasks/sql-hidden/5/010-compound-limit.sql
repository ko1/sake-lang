-- LIMIT/OFFSET after a compound, including negative values
CREATE TABLE w (word TEXT);
INSERT INTO w VALUES ('ant'), ('bee'), ('cow'), ('dog');
SELECT word FROM w UNION SELECT 'eel' ORDER BY word DESC LIMIT 2;
SELECT word FROM w UNION ALL SELECT word FROM w ORDER BY 1 LIMIT 3 OFFSET 2;
SELECT word FROM w EXCEPT SELECT 'bee' ORDER BY 1 LIMIT -5 OFFSET -2;
SELECT word FROM w INTERSECT SELECT 'cow' UNION SELECT 'ant' ORDER BY 1 LIMIT 1 OFFSET 1;
SELECT word FROM w UNION SELECT 'zebra' ORDER BY 1 LIMIT 0;
SELECT count(*) FROM (SELECT word FROM w UNION ALL SELECT word FROM w ORDER BY 1 LIMIT 5);
