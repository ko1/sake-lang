-- with DESC, PRECEDING looks at larger values; NULL is only in range of NULL
CREATE TABLE p (id INTEGER, v INTEGER);
INSERT INTO p VALUES (1,10),(2,12),(3,NULL),(4,15),(5,NULL),(6,20),(7,13);
SELECT id, v, sum(id) OVER (ORDER BY v DESC RANGE BETWEEN 3 PRECEDING AND CURRENT ROW) FROM p ORDER BY id;
SELECT id, v, count(*) OVER (ORDER BY v DESC RANGE BETWEEN CURRENT ROW AND 2 FOLLOWING) FROM p ORDER BY id;
SELECT id, v, count(v) OVER (ORDER BY v RANGE BETWEEN 2 PRECEDING AND 2 FOLLOWING), count(*) OVER (ORDER BY v RANGE BETWEEN 2 PRECEDING AND 2 FOLLOWING) FROM p ORDER BY id;
SELECT id, sum(id) OVER (ORDER BY v NULLS LAST RANGE BETWEEN 100 PRECEDING AND CURRENT ROW) FROM p ORDER BY id;
