-- LIMIT and OFFSET apply to the whole compound result
CREATE TABLE n1 (v INTEGER);
CREATE TABLE n2 (v INTEGER);
INSERT INTO n1 VALUES (5), (1), (9);
INSERT INTO n2 VALUES (7), (3), (5);
SELECT v FROM n1 UNION SELECT v FROM n2 ORDER BY v LIMIT 3;
SELECT v FROM n1 UNION SELECT v FROM n2 ORDER BY v DESC LIMIT 2 OFFSET 1;
SELECT v FROM n1 UNION ALL SELECT v FROM n2 ORDER BY v LIMIT 10 OFFSET 4;
SELECT v FROM n1 EXCEPT SELECT v FROM n2 ORDER BY 1 LIMIT 1;
SELECT v FROM n1 UNION ALL SELECT v FROM n2 ORDER BY v LIMIT -1 OFFSET 5;
