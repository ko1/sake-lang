-- a frame-start alone ends at CURRENT ROW; UNBOUNDED reaches the partition's edge
CREATE TABLE n (i INTEGER);
INSERT INTO n VALUES (1),(2),(3),(4),(5),(6);
SELECT i, sum(i) OVER (ORDER BY i ROWS 2 PRECEDING) FROM n ORDER BY i;
SELECT i, sum(i) OVER (ORDER BY i ROWS CURRENT ROW) FROM n ORDER BY i;
SELECT i, sum(i) OVER (ORDER BY i ROWS UNBOUNDED PRECEDING) FROM n ORDER BY i;
SELECT i, sum(i) OVER (ORDER BY i ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) FROM n ORDER BY i;
SELECT i, sum(i) OVER (ORDER BY i ROWS BETWEEN 1 FOLLOWING AND UNBOUNDED FOLLOWING) FROM n ORDER BY i;
SELECT i, count(*) OVER (ORDER BY i ROWS BETWEEN UNBOUNDED PRECEDING AND 2 FOLLOWING) FROM n ORDER BY i;
SELECT i, sum(i) OVER (PARTITION BY i % 2 ORDER BY i ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM n ORDER BY i;
