-- scenario: an audit trail kept beside a table, compared with set operations
CREATE TABLE price (item TEXT PRIMARY KEY, cents INTEGER NOT NULL);
CREATE TABLE audit (seq INTEGER PRIMARY KEY, item TEXT, old INTEGER, new INTEGER);
INSERT INTO price VALUES ('tea', 250), ('cake', 400), ('soup', 600);
CREATE TABLE snapshot (item TEXT, cents INTEGER);
INSERT INTO snapshot SELECT item, cents FROM price;
BEGIN;
INSERT INTO audit (item, old, new) SELECT item, cents, cents + 50 FROM price WHERE item = 'tea';
UPDATE price SET cents = cents + 50 WHERE item = 'tea';
INSERT INTO audit (item, old, new) SELECT item, cents, cents * 2 FROM price WHERE item = 'soup';
UPDATE price SET cents = cents * 2 WHERE item = 'soup';
COMMIT;
SELECT item, cents FROM price EXCEPT SELECT item, cents FROM snapshot ORDER BY item;
SELECT item, cents FROM snapshot EXCEPT SELECT item, cents FROM price ORDER BY item;
SELECT item FROM price INTERSECT SELECT item FROM snapshot ORDER BY item;
SELECT seq, item, old, new FROM audit ORDER BY seq;
BEGIN;
INSERT INTO audit (item, old, new) SELECT item, cents, 0 FROM price;
UPDATE price SET cents = 0;
SELECT sum(cents) FROM price;
ROLLBACK;
SELECT sum(cents), (SELECT count(*) FROM audit) FROM price;
WITH changes AS (SELECT item, new - old AS diff FROM audit) SELECT item, diff FROM changes ORDER BY diff DESC;
CREATE VIEW history AS SELECT item, cents AS v, 'now' AS src FROM price UNION ALL SELECT item, cents, 'then' FROM snapshot;
SELECT item, v, src FROM history WHERE item = 'soup' ORDER BY src;
SELECT src, sum(v) FROM history GROUP BY src ORDER BY src;
INSERT INTO price VALUES ('tea', 1);
INSERT INTO price VALUES ('pie', NULL);
DROP VIEW history;
DROP TABLE snapshot;
SELECT count(*) FROM history;
