-- WITH may start an INSERT
CREATE TABLE seq (n INTEGER, sq INTEGER);
WITH RECURSIVE c(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM c WHERE i < 5) INSERT INTO seq SELECT i, i * i FROM c;
SELECT n, sq FROM seq ORDER BY n;
WITH odd AS (SELECT n FROM seq WHERE n % 2 = 1) INSERT INTO seq (n) SELECT n + 100 FROM odd;
SELECT n, sq FROM seq WHERE n > 100 ORDER BY n;
WITH x AS (SELECT 1 AS a) INSERT INTO seq SELECT a FROM x;
SELECT count(*) FROM seq;
