-- scenario: a small library with views, a transaction and a schema change
CREATE TABLE book (id INTEGER PRIMARY KEY, title TEXT NOT NULL, author TEXT);
CREATE TABLE member (id INTEGER PRIMARY KEY, name TEXT UNIQUE);
CREATE TABLE loan (book_id INTEGER, member_id INTEGER, returned INTEGER DEFAULT 0);
INSERT INTO book (title, author) VALUES ('Dune', 'Herbert'), ('Emma', 'Austen'), ('Persuasion', 'Austen'), ('Ubik', 'Dick');
INSERT INTO member (name) VALUES ('ann'), ('bob'), ('cy');
INSERT INTO loan (book_id, member_id) VALUES (1, 1), (2, 1), (4, 2);
CREATE VIEW on_loan AS SELECT b.title, m.name FROM loan l JOIN book b ON b.id = l.book_id JOIN member m ON m.id = l.member_id WHERE l.returned = 0;
SELECT title, name FROM on_loan ORDER BY title;
CREATE VIEW available AS SELECT id, title FROM book EXCEPT SELECT b.id, b.title FROM book b JOIN loan l ON l.book_id = b.id WHERE l.returned = 0;
SELECT title FROM available ORDER BY title;
BEGIN;
UPDATE loan SET returned = 1 WHERE book_id = 1;
INSERT INTO loan (book_id, member_id) VALUES (3, 3);
COMMIT;
SELECT title, name FROM on_loan ORDER BY name, title;
SELECT title FROM available ORDER BY title;
INSERT INTO on_loan VALUES ('Dune', 'cy');
DROP TABLE on_loan;
DROP VIEW on_loan;
DROP VIEW available;
