INSERT INTO g VALUES (1, 0), (1, 1), (5, 1), (2, 1);
SELECT a, c FROM g WHERE a BETWEEN 1 AND 2 AND c ORDER BY a, c;
SELECT a, c FROM g WHERE a BETWEEN 0 + 1 AND 1 + 1 AND c = 0 ORDER BY a;
