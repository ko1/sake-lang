-- A compound's ORDER BY sorts under the column's collation, or a COLLATE on the term.
CREATE TABLE p (w TEXT COLLATE NOCASE);
CREATE TABLE q (w TEXT);
INSERT INTO p VALUES ('delta'), ('Bravo');
INSERT INTO q VALUES ('alpha'), ('Charlie');
SELECT w FROM p UNION ALL SELECT w FROM q ORDER BY 1;
SELECT w FROM q UNION ALL SELECT w FROM p ORDER BY 1;
SELECT w FROM q UNION ALL SELECT w FROM p ORDER BY 1 COLLATE NOCASE DESC;
SELECT w AS k FROM q UNION ALL SELECT w FROM p ORDER BY k COLLATE NOCASE;
SELECT 'Zulu' AS v UNION ALL SELECT w FROM p ORDER BY v;
