-- the compound ORDER BY takes DESC and NULLS FIRST/LAST
CREATE TABLE x (k TEXT, v INTEGER);
CREATE TABLE y (k TEXT, v INTEGER);
INSERT INTO x VALUES ('a', NULL), ('b', 2), ('c', 9);
INSERT INTO y VALUES ('d', 5), ('e', NULL), ('f', 2);
SELECT k, v FROM x UNION ALL SELECT k, v FROM y ORDER BY 2, 1;
SELECT k, v FROM x UNION ALL SELECT k, v FROM y ORDER BY 2 DESC, 1 DESC;
SELECT k, v FROM x UNION ALL SELECT k, v FROM y ORDER BY v NULLS LAST, k;
SELECT k, v FROM x UNION ALL SELECT k, v FROM y ORDER BY v DESC NULLS FIRST, k;
