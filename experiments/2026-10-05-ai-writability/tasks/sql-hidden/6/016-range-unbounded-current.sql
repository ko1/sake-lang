CREATE TABLE r (id INTEGER, tier INTEGER, amt INTEGER);
INSERT INTO r VALUES (1,2,10),(2,1,20),(3,2,30),(4,3,40),(5,1,50),(6,2,60);
SELECT id, sum(amt) OVER (ORDER BY tier RANGE UNBOUNDED PRECEDING) FROM r ORDER BY id;
SELECT id, sum(amt) OVER (ORDER BY tier RANGE BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM r ORDER BY id;
SELECT id, sum(amt) OVER (ORDER BY tier DESC RANGE BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) FROM r ORDER BY id;
SELECT id, max(amt) OVER (ORDER BY tier RANGE CURRENT ROW), min(amt) OVER (PARTITION BY tier) FROM r ORDER BY id;
SELECT id, count(*) OVER (ORDER BY tier, amt RANGE BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) FROM r ORDER BY id;
