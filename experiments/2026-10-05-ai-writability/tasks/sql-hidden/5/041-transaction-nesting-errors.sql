-- BEGIN inside a transaction, COMMIT/END/ROLLBACK outside one
CREATE TABLE t (v INTEGER);
END TRANSACTION;
BEGIN TRANSACTION;
INSERT INTO t VALUES (1);
BEGIN;
INSERT INTO t VALUES (2);
END;
END;
COMMIT TRANSACTION;
ROLLBACK;
SELECT v FROM t ORDER BY v;
BEGIN;
ROLLBACK;
ROLLBACK TRANSACTION;
SELECT count(*) FROM t;
