-- product reviews: average stars, helpfulness and reviewers
CREATE TABLE reviews (id INTEGER PRIMARY KEY, product TEXT NOT NULL, reviewer TEXT, stars INTEGER NOT NULL, helpful INTEGER DEFAULT 0);
