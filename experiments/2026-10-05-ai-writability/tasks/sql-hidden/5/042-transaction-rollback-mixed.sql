-- ROLLBACK undoes INSERT ... SELECT, UPDATE and DELETE across several tables
CREATE TABLE a (k INTEGER PRIMARY KEY, v TEXT);
CREATE TABLE b (k INTEGER, v TEXT);
INSERT INTO a (v) VALUES ('x'), ('y');
BEGIN;
INSERT INTO b SELECT k, v FROM a;
UPDATE a SET v = upper(v);
DELETE FROM a WHERE k = 1;
INSERT INTO a (v) VALUES ('z');
SELECT k, v FROM a UNION ALL SELECT k, v FROM b ORDER BY 1, 2;
ROLLBACK;
SELECT k, v FROM a UNION ALL SELECT k, v FROM b ORDER BY 1, 2;
INSERT INTO a (v) VALUES ('w');
SELECT max(k) FROM a;
