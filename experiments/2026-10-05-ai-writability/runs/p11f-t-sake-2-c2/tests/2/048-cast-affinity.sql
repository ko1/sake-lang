-- a CAST has the affinity of its type
SELECT CAST('12' AS INTEGER) = '12', '12' = 12, CAST(12 AS TEXT) = 12, CAST(12 AS TEXT) = 12.0;
SELECT CAST(5 AS REAL) = '5.0', CAST('5' AS TEXT) < 6, 5 < '6';
CREATE TABLE c (s TEXT);
INSERT INTO c VALUES ('10'), ('9'), ('100');
SELECT s FROM c ORDER BY s;
SELECT s FROM c ORDER BY CAST(s AS INTEGER);
SELECT s FROM c WHERE CAST(s AS INTEGER) > '50' ORDER BY s;
