SELECT name, count(l.book_id) FROM member m LEFT JOIN loan l ON l.member_id = m.id GROUP BY m.id ORDER BY m.id;
WITH busy AS (SELECT member_id FROM loan GROUP BY member_id HAVING count(*) > 1) SELECT name FROM member WHERE id IN (SELECT member_id FROM busy);
