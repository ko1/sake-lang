-- RANGE CURRENT ROW means the first peer as a start and the last peer as an end
CREATE TABLE g (id INTEGER, lvl INTEGER);
INSERT INTO g VALUES (1,1),(2,2),(3,2),(4,3),(5,3),(6,3),(7,4);
SELECT id, count(*) OVER (ORDER BY lvl RANGE CURRENT ROW) FROM g ORDER BY id;
SELECT id, sum(id) OVER (ORDER BY lvl RANGE BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) FROM g ORDER BY id;
SELECT id, sum(id) OVER (ORDER BY lvl RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) FROM g ORDER BY id;
SELECT id, sum(id) OVER (ORDER BY lvl ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) FROM g ORDER BY id;
SELECT id, count(*) OVER (ORDER BY lvl RANGE BETWEEN CURRENT ROW AND CURRENT ROW), max(id) OVER (ORDER BY lvl RANGE CURRENT ROW) FROM g ORDER BY id;
