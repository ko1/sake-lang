-- NULLs are equal to each other when rows are compared in compounds
SELECT NULL UNION SELECT NULL;
SELECT NULL, 1 INTERSECT SELECT NULL, 1;
SELECT NULL EXCEPT SELECT NULL;
SELECT count(*) FROM (SELECT NULL AS z UNION ALL SELECT NULL);
CREATE TABLE t (a INTEGER, b INTEGER);
INSERT INTO t VALUES (NULL, NULL), (NULL, 1), (1, NULL);
SELECT a, b FROM t UNION SELECT NULL, NULL ORDER BY a, b;
SELECT a, b FROM t EXCEPT SELECT b, a FROM t WHERE a IS NULL ORDER BY a, b;
