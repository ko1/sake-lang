-- ROWS BETWEEN n PRECEDING AND m FOLLOWING, clipped to the partition
CREATE TABLE v (t INTEGER, s TEXT, x INTEGER);
INSERT INTO v VALUES (1,'a',4),(2,'a',8),(3,'a',6),(4,'a',2),(5,'a',10),(1,'b',1),(2,'b',3);
SELECT s, t, avg(x) OVER (PARTITION BY s ORDER BY t ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM v ORDER BY s, t;
SELECT s, t, sum(x) OVER (PARTITION BY s ORDER BY t ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) FROM v ORDER BY s, t;
SELECT s, t, count(*) OVER (PARTITION BY s ORDER BY t ROWS BETWEEN CURRENT ROW AND 2 FOLLOWING) FROM v ORDER BY s, t;
SELECT t, max(x) OVER (ORDER BY s, t ROWS BETWEEN 3 PRECEDING AND 1 PRECEDING) FROM v ORDER BY s, t;
SELECT t, min(x) OVER (ORDER BY s, t ROWS BETWEEN 1 FOLLOWING AND 2 FOLLOWING) FROM v ORDER BY s, t;
