-- RANGE n PRECEDING / n FOLLOWING compare the ORDER BY value
CREATE TABLE ev (id INTEGER, at INTEGER);
INSERT INTO ev VALUES (1,0),(2,3),(3,4),(4,10),(5,11),(6,11),(7,20);
SELECT id, at, count(*) OVER (ORDER BY at RANGE BETWEEN 5 PRECEDING AND CURRENT ROW) FROM ev ORDER BY id;
SELECT id, at, count(*) OVER (ORDER BY at RANGE BETWEEN CURRENT ROW AND 1 FOLLOWING) FROM ev ORDER BY id;
SELECT id, sum(id) OVER (ORDER BY at RANGE BETWEEN 3 PRECEDING AND 3 FOLLOWING) FROM ev ORDER BY id;
SELECT id, min(at) OVER (ORDER BY at RANGE 10 PRECEDING) FROM ev ORDER BY id;
SELECT id, count(*) OVER (ORDER BY at RANGE BETWEEN 1 FOLLOWING AND 6 FOLLOWING) FROM ev ORDER BY id;
SELECT id, count(*) OVER (ORDER BY at RANGE BETWEEN 0 PRECEDING AND 0 FOLLOWING) FROM ev ORDER BY id;
