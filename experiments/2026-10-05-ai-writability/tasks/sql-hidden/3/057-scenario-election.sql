-- election: votes per candidate and district, turnout
CREATE TABLE districts (name TEXT PRIMARY KEY, voters INTEGER NOT NULL);
CREATE TABLE votes (district TEXT NOT NULL, candidate TEXT, n INTEGER NOT NULL);
