SELECT i, count(i) OVER win, sum(i) OVER win, total(i) OVER win, avg(i) OVER win FROM e
  WINDOW win AS (PARTITION BY g ORDER BY i ROWS BETWEEN 1 FOLLOWING AND 5 FOLLOWING) ORDER BY i;
SELECT i, min(w) OVER win, max(w) OVER win, group_concat(w) OVER win FROM e
  WINDOW win AS (PARTITION BY g ORDER BY i ROWS BETWEEN 2 PRECEDING AND 1 PRECEDING) ORDER BY i;
SELECT i, first_value(w) OVER win, last_value(w) OVER win, nth_value(w, 1) OVER win FROM e
  WINDOW win AS (ORDER BY i RANGE BETWEEN 5 FOLLOWING AND 9 FOLLOWING) ORDER BY i;
SELECT i, count(*) OVER (ORDER BY i ROWS BETWEEN 2 PRECEDING AND 3 PRECEDING), row_number() OVER (ORDER BY i ROWS BETWEEN 2 PRECEDING AND 3 PRECEDING) FROM e ORDER BY i;
