-- compound operators have equal precedence and associate to the left
SELECT 1 UNION SELECT 2 EXCEPT SELECT 1 ORDER BY 1;
SELECT 1 EXCEPT SELECT 1 UNION SELECT 2 ORDER BY 1;
SELECT 1 UNION ALL SELECT 1 UNION SELECT 1;
SELECT 1 UNION SELECT 1 UNION ALL SELECT 1;
SELECT 1 UNION SELECT 2 INTERSECT SELECT 2 ORDER BY 1;
SELECT 3 INTERSECT SELECT 3 UNION ALL SELECT 3 ORDER BY 1;
