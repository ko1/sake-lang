-- ORDER BY with blobs among other values
CREATE TABLE v (id INTEGER, x BLOB);
INSERT INTO v VALUES (1, X'0102'), (2, X'01'), (3, X'FF'), (4, NULL), (5, X''), (6, X'7A');
SELECT id, x FROM v ORDER BY x;
SELECT id, x FROM v ORDER BY x DESC;
SELECT id FROM v ORDER BY x DESC NULLS FIRST;
SELECT x, id FROM v WHERE x > X'01' ORDER BY 1 LIMIT 2;
SELECT y FROM (SELECT 'b' AS y UNION ALL SELECT X'61' UNION ALL SELECT 3 UNION ALL SELECT NULL UNION ALL SELECT 'a') ORDER BY y;
